"""The app icon, from one geometry: a gold Chi-Rho on a lapis-to-night gradient, the Chi passing under the Rho.
   python3 tools/icon.py          writes the SVG master and the Android vector drawables
   node tools/icon_render.js      then renders the PNGs (launcher fallbacks, android/icon512.png, maskable) with Chromium
Grid: 108 x 108 units (the Android adaptive-icon canvas; the safe zone is the circle r=33 around the centre)."""
import os
R = os.path.abspath(os.path.join(os.path.dirname(__file__), '..')) + '/'

STEM = 'M54 27 V83'
BOWL = 'M54 29.5 H59 A9 9 0 0 1 59 47.5 H54'
CHI = 'M40.5 51.5 L67.5 75 M67.5 51.5 L40.5 75'
W = 4.8                     # stroke width
GAP = W / 2 + 2.1           # the Chi stops this far either side of the stem's centre line
RING = (54, 55, 33)         # cx, cy, r
GOLD = [(0, '#f6dc96'), (.5, '#e2b85b'), (1, '#b8862c')]
BG = [(0, '#22305e'), (.55, '#141a33'), (1, '#0b0c10')]
NIGHT = '#0b0c10'
ADAPTIVE_SCALE = .88        # the glyph inside launcher masks and the Android 12 splash circle


def svg_defs():
    st = lambda s: ''.join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in s)
    return ('<defs>'
            f'<linearGradient id="bg" x1="0" y1="0" x2="108" y2="108" gradientUnits="userSpaceOnUse">{st(BG)}</linearGradient>'
            '<radialGradient id="glow" cx="54" cy="49.7" r="54" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#e2b85b" stop-opacity=".22"/><stop offset="1" stop-color="#e2b85b" stop-opacity="0"/></radialGradient>'
            f'<linearGradient id="gold" x1="0" y1="25" x2="0" y2="85" gradientUnits="userSpaceOnUse">{st(GOLD)}</linearGradient>'
            f'<clipPath id="chi"><path d="M0 0H{54 - GAP}V108H0Z M{54 + GAP} 0H108V108H{54 + GAP}Z"/></clipPath>'
            '</defs>')


def svg_glyph(paint='url(#gold)', ring=True):
    cx, cy, r = RING
    g = f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{paint}" stroke-width="1.1" opacity=".42"/>' if ring else ''
    return (g + f'<g fill="none" stroke="{paint}" stroke-width="{W}" stroke-linecap="round" stroke-linejoin="round">'
            f'<path d="{CHI}" clip-path="url(#chi)"/><path d="{STEM} {BOWL}"/></g>')


def svg_icon(radius=24, scale=1.0):
    """The full icon. radius 24 = the rounded square used for the PNG fallbacks; 0 = full bleed (maskable)."""
    t = f' transform="translate(54 54) scale({scale}) translate(-54 -54)"' if scale != 1 else ''
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="512" height="512">{svg_defs()}'
            f'<rect width="108" height="108" rx="{radius}" fill="url(#bg)"/><rect width="108" height="108" rx="{radius}" fill="url(#glow)"/>'
            f'<g{t}>{svg_glyph()}</g></svg>')


def svg_mark(size=24):
    """The bare glyph in gold, for the page (favicon, splash)."""
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="{size}" height="{size}">{svg_defs()}{svg_glyph()}</svg>'


# ---- Android vector drawables ----
A = 'xmlns:android="http://schemas.android.com/apk/res/android"'
AAPT = 'xmlns:aapt="http://schemas.android.com/aapt"'


def v_grad(attr, stops, **k):
    xs = ' '.join(f'android:{a}="{v}"' for a, v in k.items())
    items = ''.join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in stops)
    return f'<aapt:attr name="android:{attr}"><gradient {xs}>{items}</gradient></aapt:attr>'


def vector(body, size=108, aapt=True):
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/icon.py -->\n<vector {A}{" " + AAPT if aapt else ""} android:width="{size}dp" android:height="{size}dp" '
            f'android:viewportWidth="108" android:viewportHeight="108">\n{body}\n</vector>\n')


def v_glyph(gold=True, ring=True, color='#FFFFFFFF'):
    gl = lambda: v_grad('strokeColor', GOLD, type='linear', startX=0, startY=25, endX=0, endY=85) if gold else ''
    sc = '' if gold else f' android:strokeColor="{color}"'
    cx, cy, r = RING
    out = ''
    if ring:
        out += (f'<path android:pathData="M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0" android:strokeWidth="1.1" android:strokeAlpha="0.42"{sc}>'
                f'{gl()}</path>\n')
    out += (f'<group><clip-path android:pathData="M0,0H{54 - GAP}V108H0Z M{54 + GAP},0H108V108H{54 + GAP}Z"/>'
            f'<path android:pathData="{CHI}" android:strokeWidth="{W}" android:strokeLineCap="round"{sc}>{gl()}</path></group>\n'
            f'<path android:pathData="{STEM} {BOWL}" android:strokeWidth="{W}" android:strokeLineCap="round" android:strokeLineJoin="round"{sc}>{gl()}</path>')
    return f'<group android:pivotX="54" android:pivotY="54" android:scaleX="{ADAPTIVE_SCALE}" android:scaleY="{ADAPTIVE_SCALE}">\n{out}\n</group>'


def main():
    w = lambda path, s: open(R + path, 'w', encoding='utf-8').write(s)
    w('android/icon.svg', svg_icon())
    w('android/icon-full.svg', svg_icon(0))                              # iOS home screen (iOS rounds the corners itself)
    w('android/icon-maskable.svg', svg_icon(0, ADAPTIVE_SCALE * .92))   # PWA maskable: inside the 80% safe circle
    d = 'android/res/drawable/'
    w(d + 'ic_launcher_fg.xml', vector(v_glyph()))
    w(d + 'ic_launcher_mono.xml', vector(v_glyph(gold=False, ring=False), aapt=False))
    w(d + 'ic_launcher_bg.xml', vector(
        '<path android:pathData="M0,0H108V108H0Z">' + v_grad('fillColor', BG, type='linear', startX=0, startY=0, endX=108, endY=108) + '</path>\n'
        '<path android:pathData="M0,0H108V108H0Z">' + v_grad('fillColor', [(0, '#38E2B85B'), (1, '#00E2B85B')], type='radial', centerX=54, centerY=49.7, gradientRadius=54) + '</path>'))
    os.makedirs(R + 'android/res/mipmap-anydpi-v26', exist_ok=True)
    w('android/res/mipmap-anydpi-v26/ic_launcher.xml',
      '<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/icon.py -->\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
      '    <background android:drawable="@drawable/ic_launcher_bg"/>\n    <foreground android:drawable="@drawable/ic_launcher_fg"/>\n'
      '    <monochrome android:drawable="@drawable/ic_launcher_mono"/>\n</adaptive-icon>\n')
    # notification icon: the same glyph, white, filling a 24dp canvas
    w(d + 'ic_stat.xml',
      '<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/icon.py -->\n'
      f'<vector {A} android:width="24dp" android:height="24dp" android:viewportWidth="108" android:viewportHeight="108">\n'
      f'<group android:pivotX="54" android:pivotY="55" android:scaleX="{round(108 / 62, 4)}" android:scaleY="{round(108 / 62, 4)}">'
      f'<group><clip-path android:pathData="M0,0H{54 - GAP}V108H0Z M{54 + GAP},0H108V108H{54 + GAP}Z"/>'
      f'<path android:pathData="{CHI}" android:strokeWidth="{W * 1.1}" android:strokeLineCap="round" android:strokeColor="#FFFFFFFF"/></group>'
      f'<path android:pathData="{STEM} {BOWL}" android:strokeWidth="{W * 1.1}" android:strokeLineCap="round" android:strokeLineJoin="round" android:strokeColor="#FFFFFFFF"/>'
      '</group>\n</vector>\n')
    print('icon sources written')


if __name__ == '__main__':
    main()
